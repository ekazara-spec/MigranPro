function inferSponsorArea(name: string): string {
  const upper = name.toUpperCase();
  if (upper.includes("KARAWANG")) return "Karawang";
  if (upper.includes("CIANJUR")) return "Cianjur";
  if (upper.includes("SUKABUMI")) return "Sukabumi";
  if (upper.includes("PURWAKARTA") || upper.includes("PWK")) return "Purwakarta";
  if (upper.includes("SUBANG")) return "Subang";
  if (upper.includes("BREBES")) return "Brebes";
  if (upper.includes("SERANG")) return "Serang";
  if (upper.includes("NTB") || upper.includes("LOMBOK") || upper.includes("SUMBAWA")) return "NTB / Lombok / Sumbawa";
  if (upper.includes("KALIMANTAN")) return "Kalimantan";
  if (upper.includes("MJLK")) return "Majalengka";
  return "Mitra Lapangan 2026";
}

export function createExcel2026Sponsors(): Sponsor[] {
  return SPONSOR_2026_EXCEL_NAMES.map((rawName, idx) => {
    const seq = String(idx + 1).padStart(3, "0");
    const name = rawName.trim();
    return {
      id: `sp-2026-${seq}`,
      code: `PL-2026-${seq}`,
      name,
      phone: "-",
      area: inferSponsorArea(name),
      branchId: "br-jkt",
      bankAccount: "-",
      commissionPerCpmi: 4500000,
      paidAmount: 0,
      payableAmount: 0,
    };
  });
}
